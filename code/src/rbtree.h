#ifndef RBTREE_H
#define RBTREE_H

#include<bits/stdc++.h>
using namespace std;

/*
题目问的是：恰好 n 个内部结点、且满足红黑树五条性质的有序二叉树有多少种（左右儿子不同算不同）。

五条性质里只有两条会参与计数：根必须黑；红点的两个儿子必须黑。剩下三条（每个点非红即黑、
NULL 是黑叶子、每条到叶子的路径黑点数相同）合起来给出一个可以逐层拆的量——黑高。
把一棵子树用（黑高 h，内部结点数 n）两个参数描述，形状就不必单独枚举了：
给定 n 和 h，根的颜色定了，两个儿子的黑高也就定了，剩下的只是把 n-1 个结点分给左右两棵子树。

唯一容易错的边界是红点可以当叶子：它的两个儿子都是 NULL，黑高为 0。
所以空树必须记成"黑高 0 的黑子树"（b[0][0]=1），不能记 0——
否则红根挂在两个 NULL 上这种树全被丢掉，n=5 会数出 2 而不是样例给的 8。

规模：n ≤ 500，黑高 h 满足 2^h-1 ≤ n，所以 h ≤ 8，表只有 9 层。
*/

const int MOD=1000000007;

/*
三张表都只按（黑高, 结点数）索引。b 是黑根子树的个数，r 是红根子树的个数，t=b+r 记一份和。
拆成三张而不是两张，是因为黑根那一条要用"儿子可以是黑根也可以是红根"，每次现场加一遍
比留一行 t[h][m]=(b+r)%MOD 更绕；反正 t 也是一遍 O(n) 就能填满的。
*/
struct Counter{
    int n;                          // 题面给的 n，表的列数是 n+1（0 号列是空树）
    int hmax;                       // 可能出现的最大的黑高
    long long mults;                // 乘法次数，只给实验用
    vector<vector<int>> b,r,t;

    explicit Counter(int n);
    void build();
    int solve();
};

int count(int n);

#endif
